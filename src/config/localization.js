export function getLocalizedStrings(locale) {
  return translations[locale] || translations.en;
}

export function createTranslator(locale) {
  const strings = getLocalizedStrings(locale);
  const fallback = translations.en;

  return (key) => {
    const read = (source) => key.split('.').reduce((value, part) => (value && value[part] !== undefined ? value[part] : undefined), source);
    return read(strings) ?? read(fallback) ?? key;
  };
}

export function getAllServices(locale) {
  return getLocalizedStrings(locale).servicesList.map((service, index) => ({
    ...service,
    id: serviceSectionIds[index] || service.title
  }));
}

export function localizeDigits(text, locale) {
  if (locale !== 'ar') return text;
  return String(text).replace(/\d/g, (digit) => String.fromCharCode(1632 + Number(digit)));
}